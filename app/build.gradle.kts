// Push needs the Firebase project's config. Without it the app still builds and runs;
// it just never registers a device, and the server emails and texts instead.
if (file("google-services.json").exists()) {
    apply(plugin = libs.plugins.google.services.get().pluginId)
} else {
    logger.warn("app/google-services.json is missing — building without push notifications.")
}

fun apiBaseUrl(buildType: String): String =
    (project.findProperty("fundaza.apiBaseUrl.$buildType") as String?)
        ?: error("Set fundaza.apiBaseUrl.$buildType in gradle.properties")

